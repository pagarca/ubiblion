#!/usr/bin/env python3
"""Turns the images in assets/screensavers/ into src/screensavers.h.

    pip install pillow
    python tools/make_screensavers.py

Each image (PNG or JPG, any size) is cropped to a centred square, scaled to
200x200 and dithered to black and white; transparent areas become white. They
are shown in file-name order. Every one costs 5000 bytes of program flash, so
rebuild and upload the firmware afterwards.
"""

from pathlib import Path

from PIL import Image, ImageOps

SIZE = 200
ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets" / "screensavers"
OUTPUT = ROOT / "src" / "screensavers.h"


def convert(path):
    """Returns the packed bitmap: one bit per pixel, MSB first, 1 = black."""
    image = ImageOps.exif_transpose(Image.open(path)).convert("RGBA")
    white = Image.new("RGBA", image.size, "white")
    gray = Image.alpha_composite(white, image).convert("L")
    square = ImageOps.fit(gray, (SIZE, SIZE), Image.LANCZOS)
    # Inverted before dithering so that set bits mean ink.
    return ImageOps.invert(square).convert("1").tobytes()


def main():
    images = sorted(p for p in SOURCE.iterdir() if p.suffix.lower() in (".png", ".jpg", ".jpeg"))
    if not images:
        raise SystemExit(f"No PNG or JPG images in {SOURCE}")

    lines = [
        "// Generated by tools/make_screensavers.py from assets/screensavers/.",
        "// Don't edit by hand.",
        "#pragma once",
        "",
        "#include <Arduino.h>",
        "",
        "namespace Screensavers {",
        "",
    ]
    for index, path in enumerate(images):
        data = convert(path)
        assert len(data) == SIZE * SIZE // 8
        lines.append(f"// {path.name}")
        lines.append(f"static const uint8_t kImage{index}[] PROGMEM = {{")
        for start in range(0, len(data), 16):
            lines.append("    " + " ".join(f"0x{b:02X}," for b in data[start : start + 16]))
        lines.append("};")
        lines.append("")
    names = ", ".join(f"kImage{i}" for i in range(len(images)))
    lines += [
        f"static const uint8_t* const kImages[] = {{{names}}};",
        f"static const uint8_t COUNT = {len(images)};",
        "",
        "}  // namespace Screensavers",
    ]
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUTPUT.relative_to(ROOT)}: {len(images)} images, {len(images) * SIZE * SIZE // 8} bytes")


if __name__ == "__main__":
    main()
